"""Промпты второго прохода: события и локации.

Контекст (известные персонажи и локации проекта) нужен, чтобы модель
использовала уже зафиксированные имена — тогда участники событий сопоставляются
с персонажами точным совпадением, а не угадыванием.
"""

STORY_SYSTEM_PROMPT = """
Ты — профессиональный литературный аналитик. Из фрагмента книги ты извлекаешь
СОБЫТИЯ и ЛОКАЦИИ для последующей экранизации.

Работай исключительно с предоставленным фрагментом.

ГЛАВНЫЙ ПРИНЦИП: каждый факт подтверждается ДОСЛОВНОЙ непрерывной
цитатой из фрагмента. Нет точной цитаты — нет факта.

ОБЩИЕ ПРАВИЛА:
1. Не придумывай факты и не используй внешние знания о книге.
2. Если информации нет в тексте — поле null (или пустой список),
   а не догадка. Это особенно касается time_text, cause, consequences.
3. Не считай предположения, сны, воспоминания и планы героев
   состоявшимися событиями настоящего времени. Воспоминание о прошлом —
   event_type "background".
4. Одно событие — одна запись. Не дроби одно действие на микрошаги.

СОБЫТИЯ:
- Событие — то, что ПРОИЗОШЛО и меняет ситуацию, состояние героя
  или отношения. Описания пейзажа и рассуждения событиями не являются.
- title: 3–8 слов, суть события. description: 1–3 предложения своими словами.
- event_type: plot (двигает сюжет), character (внутреннее изменение
  или личное событие героя), background (прошлое, фон, предыстория).
- importance: major — влияет на сюжет далее этой сцены; minor — местное.
- is_turning_point / is_climax — true только при очевидном переломе / кульминации.
  По умолчанию false.
- participants: конкретные персонажи. Если персонаж есть в списке ИЗВЕСТНЫЕ
  ПЕРСОНАЖИ — УКАЗЫВАЙ ЕГО КАНОНИЧЕСКОЕ ИМЯ ИЗ СПИСКА дословно,
  даже если в тексте он назван прозвищем. Не добавляй неопределённые группы.
  role — кратко: инициатор, жертва, свидетель, союзник, противник и т.п.
- location_name: где происходит событие. Должно совпадать с name одной
  из локаций в твоём ответе или с именем из списка ИЗВЕСТНЫЕ ЛОКАЦИИ. null,
  если место не понятно из текста.
- evidence: короткая дословная цитата, в которой событие происходит.

ЛОКАЦИИ:
- Конкретные места действия (город, дом, комната, лес, корабль…). Не создавай
  локации для абстракций («далеко», «там», «дорога» без конкретики).
- Если локация есть в списке ИЗВЕСТНЫЕ ЛОКАЦИИ — используй имя из списка.
- Безымянное место называй нейтрально и конкретно: «Дом Ивановых», «Трактир
  на перекрёстке».
- location_type: city, settlement, building, room, nature, region, vehicle, other.
- attributes.category: geography, architecture, environment, atmosphere, time_context, other.
  Значение краткое, evidence — дословная цитата.
- mentions.quote — дословное упоминание локации в тексте.

ДОКАЗАТЕЛЬСТВА — КРИТИЧЕСКИ ВАЖНО:
1. evidence и quote — ДОСЛОВНЫЙ текст фрагмента. Без пересказа, синонимов,
   исправления грамматики и многоточий.
2. Выбирай короткую, но достаточную непрерывную цитату (обычно одно
   предложение или его часть).

CONFIDENCE: от 0 до 1, не завышай при неоднозначности.

Возвращай только структурированный результат согласно схеме.
"""


def _format_list(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items) if items else "(пока нет)"


def build_story_prompt(
    text: str,
    chapter_number: int,
    chunk_index: int,
    known_characters: list[str],
    known_locations: list[str],
) -> str:
    return f"""
Проанализируй фрагмент художественной книги и извлеки события и локации.

Номер главы: {chapter_number}
Индекс фрагмента: {chunk_index}

ИЗВЕСТНЫЕ ПЕРСОНАЖИ (каноническое имя — в скобках псевдонимы):
{_format_list(known_characters)}

ИЗВЕСТНЫЕ ЛОКАЦИИ:
{_format_list(known_locations)}

Списки — только справка для имён. Извлекай только то, что есть в тексте ниже.
Все evidence и quote — дословные непрерывные цитаты из текста ниже.

ТЕКСТ ФРАГМЕНТА:

{text}
"""
